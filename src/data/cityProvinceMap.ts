// SVG 省份 ID -> 该省份下可选的城市名列表（便于反向查找）
export const provinceToCities = Object.entries(cityToProvince).reduce(
  (acc, [city, provinceId]) => {
    if (!acc[provinceId]) acc[provinceId] = []
    acc[provinceId].push(city)
    return acc
  },
  {} as Record<string, string[]>,
)
